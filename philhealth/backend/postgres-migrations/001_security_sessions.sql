-- Application-owned security state for the existing PostgreSQL database.
-- This migration only creates new tables and indexes; it never alters or deletes
-- existing business records. Run only after review and backup approval.

BEGIN;

CREATE TABLE IF NOT EXISTS app_sessions (
  id text PRIMARY KEY,
  user_id integer REFERENCES users(user_id) ON DELETE CASCADE,
  csrf_token text NOT NULL,
  expires_at timestamptz NOT NULL,
  last_seen_at timestamptz NOT NULL,
  cap_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT app_sessions_expiry_check CHECK (expires_at <= cap_at)
);

CREATE INDEX IF NOT EXISTS idx_app_sessions_expiry ON app_sessions (expires_at);
CREATE INDEX IF NOT EXISTS idx_app_sessions_user ON app_sessions (user_id);

CREATE TABLE IF NOT EXISTS app_login_attempts (
  attempt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(64) NOT NULL,
  ip inet NOT NULL,
  attempted_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  successful boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_app_login_attempts_lockout
  ON app_login_attempts (username, ip, attempted_at DESC)
  WHERE successful = false;

COMMIT;
